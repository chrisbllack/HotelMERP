// 6. CASH FLOW 30-DAY PROJECTION ENGINE
// ==========================================

export function generateCashFlowForecast(
  startDateStr: string,
  reservations: Reservation[],
  cityLedgerAccounts: CityLedgerAccount[],
  accountsPayableInvoices: AccountsPayableInvoice[],
  employees: Employee[],
  scenario: CashFlowScenario = { occupancyAdjustmentPct: 0, arCollectionDelayDays: 0, capexFreeze: false }
): DailyCashFlowEntry[] {
  // Opening Treasury balance on Day 1
  let currentBalance = 142500000; // ₦142.5M
  const minLiquidityReserve = 60000000; // ₦60.0M threshold

  const grossMonthlyPayroll = employees.reduce((acc, e) => acc + (e.salary || 0), 0) || 38200000;
  const netMonthlyPayroll = Math.round(grossMonthlyPayroll * 0.88);
  const midMonthServiceChargePool = 9400000; // 10% pool distributed on 15th

  const entries: DailyCashFlowEntry[] = [];
  const start = new Date(startDateStr || "2026-09-08");

  const dayNames = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];

  for (let i = 0; i < 30; i++) {
    const d = new Date(start);
    d.setDate(start.getDate() + i);
    const dateIso = d.toISOString().slice(0, 10);
    const dayOfWeek = d.getDay(); // 0 = Sun, 5 = Fri, 6 = Sat
    const dayOfMonth = d.getDate();
    const dayName = dayNames[dayOfWeek];

    // Base Occupancy & Room Revenue Model
    // Weekend leisure bump, weekday corporate stays
    const isWeekend = dayOfWeek === 5 || dayOfWeek === 6;
    const baseOccupancyMultiplier = (isWeekend ? 1.15 : 1.0) * (1 + scenario.occupancyAdjustmentPct / 100);

    // Inflows from current and projected reservations
    const roomSettlements = Math.round((isWeekend ? 8200000 : 6400000) * baseOccupancyMultiplier);
    const roomDeposits = Math.round((dayOfWeek === 1 || dayOfWeek === 2 ? 5500000 : 3800000) * baseOccupancyMultiplier);
    const fnbRevenue = Math.round((isWeekend ? 4900000 : 3400000) * baseOccupancyMultiplier);
    const otherInflow = Math.round(1100000 * baseOccupancyMultiplier);

    // Corporate City Ledger AR Collections
    // Scheduled on corporate settlement days (typically Thursdays/Fridays, or delayed by scenario)
    let arCollections = 0;
    const effectiveDay = i - scenario.arCollectionDelayDays;
    if (effectiveDay === 2) arCollections = 14500000; // Total Energies clearing
    else if (effectiveDay === 6) arCollections = 22400000; // Shell Nigeria clearing
    else if (effectiveDay === 13) arCollections = 18600000; // Chevron clearing
    else if (effectiveDay === 20) arCollections = 16800000; // PwC & KPMG clearing
    else if (effectiveDay === 27) arCollections = 19200000; // NNPC Corporate clearing
    else if (dayOfWeek === 4) arCollections = 2500000; // Routine direct bill wire

    const totalInflow = roomSettlements + roomDeposits + arCollections + fnbRevenue + otherInflow;

    // Outflows
    let payrollOutflow = 0;
    if (dayOfMonth === 25 || (dayOfMonth === 24 && dayOfWeek === 5)) {
      payrollOutflow = netMonthlyPayroll; // Base payroll run
    } else if (dayOfMonth === 15) {
      payrollOutflow = midMonthServiceChargePool; // Service charge distribution
    } else if (dayOfWeek === 5) {
      payrollOutflow = 1200000; // Casual banquet staff / weekend temp wages
    }

    // Vendor AP Payments
    let apOutflow = Math.round(1600000 + (isWeekend ? 800000 : 0)); // Daily F&B deliveries COD/Net 7
    if (i === 4 || i === 18) {
      apOutflow += 12500000; // Major weekly vendor batch payment run
    }

    // Utilities & Diesel Fuel Delivery
    let utilityOutflow = Math.round(450000);
    if (i === 3 || i === 17) {
      utilityOutflow += 9200000; // Bulk diesel fuel tank top-up (33,000 Liters)
    }

    // Statutory Taxes (VAT 7.5% & Consumption Tax 5% due on 21st of month)
    let taxOutflow = 0;
    if (dayOfMonth === 21) {
      taxOutflow = 16200000; // FIRS & LIRS monthly remittance
    }

    // Loan Service / Capex Chiller instalments
    let capexOutflow = 0;
    if (!scenario.capexFreeze) {
      if (i === 9) capexOutflow = 14500000; // Chiller overhaul progress milestone
      if (i === 24) capexOutflow = 8000000; // FF&E refurbishment reserve
    }

    const totalOutflow = payrollOutflow + apOutflow + utilityOutflow + taxOutflow + capexOutflow;
    const netCash = totalInflow - totalOutflow;
    const openingBal = currentBalance;
    const closingBal = openingBal + netCash;
    currentBalance = closingBal;

    let notes = "";
    if (payrollOutflow > 10000000) notes = "Monthly net staff payroll disbursement";
    else if (taxOutflow > 0) notes = "FIRS VAT & LIRS State Hotel Consumption Tax remittance";
    else if (arCollections > 15000000) notes = "Major corporate direct-bill wire receipt";
    else if (utilityOutflow > 5000000) notes = "Bulk diesel generator fuel delivery (33,000L)";
    else if (capexOutflow > 0) notes = "HVAC Chiller capital milestone expenditure";

    entries.push({
      date: dateIso,
      dayNumber: i + 1,
      dayName,
      inflows: {
        roomRevenueSettlements: roomSettlements,
        roomAdvanceDeposits: roomDeposits,
        cityLedgerCollections: arCollections,
        fnbAndOutletsRevenue: fnbRevenue,
        otherOperatingInflows: otherInflow,
        totalInflow,
      },
      outflows: {
        payrollAndWages: payrollOutflow,
        vendorAccountsPayable: apOutflow,
        utilitiesAndDiesel: utilityOutflow,
        statutoryTaxes: taxOutflow,
        loanServiceAndCapex: capexOutflow,
        totalOutflow,
      },
      netCashFlow: netCash,
      openingBalance: openingBal,
      closingBalance: closingBal,
      isMinReserveBreached: closingBal < minLiquidityReserve,
      notes,
    });
  }

  return entries;
}

